/* ============================================================
   RTLS visualization - content model (data only)
   ------------------------------------------------------------
   Pure data, no DOM/behavior. Consumed by app.js. Numbers come
   from model.js - never hardcode a figure here that model.js can
   compute, or the two will drift.

   SIX SOURCES, ONE PANEL SHAPE. Every clickable thing on the page
   resolves to an entry in one of these maps, and app.js renders
   them all with the same function:

     PANELS[id]    ← data-node="id"     SVG node on a diagram
     METHODS[id]   ← data-method="id"   measurement method card
     TECH[id]      ← data-tech="id"     radio row (keys === RADIO in model.js)
     CASES[id]     ← data-case="id"     use-case card
     PITFALLS[id]  ← data-pitfall="id"  pilot pitfall
     GLOSSARY[id]  ← data-term="id"     term chip, works on EVERY layer

   Panel shape (every field optional except kind + lead):
     kind    {string}  panel title
     badge   {string}  small chip next to the kind
     scope   {string}  mono subtitle
     owner   {object}  {who, label?, freq?} - who buys/owns this.
                       `who` picks the hue via [data-owner] in styles.css,
                       so keep it one of 'ИТ' / 'эксплуатация' /
                       'охрана труда' / 'вендор'.
     lead    {string}  intro paragraph, HTML allowed
     fields  {[name, descHTML][]}       → «Характеристики»
     chain   {[label, valueHTML][]}     → «Цепочка решения» (cases)
     refs    {[dir, verb, target, via][]} → «Связи»; dir 'out' = this → target
     verify  {[{cmd, ok?, bad?}]}       → «Как проверить на объекте»
     ask     {[stringHTML]}             → «Что спросить у поставщика»
     note    {string}  amber callout
     data    {object}  enables the «Данные» pane:
       code   {string} payload with keys wrapped as
                       <span class="yk" data-f="KEY">…</span>
       lang   {string} label of the fragment
       fields {KEY: {purpose, links[], impact, failure?}}  KEY === data-f

   ID CONTRACTS THAT BREAK SILENTLY (see README «Ключевой контракт»):
     · CASES[*].method MUST be a key of METHODS
     · CASES[*].tech   MUST be a key of TECH and of RADIO (model.js)
     · TECH keys       MUST equal RADIO keys exactly, both ways
     · METHODS[*].minAnchors is NOT stored - it comes from minAnchors()
     · every data-term in any layer MUST exist here, and every
       GLOSSARY entry MUST be referenced at least once
   All five are checked by ?selftest=1.
   ============================================================ */

